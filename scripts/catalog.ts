/**
 * Writes src/practice/catalog.gen.ts: titles, genres, word counts and dates for every RC set, VA paragraph and critical reasoning question,
 * and src/practice/leads.gen.ts: each passage's opening paragraph, which only the home page loads.
 * The main bundle uses the catalog; the full passages load only when a practice page needs them.
 * Run with `npm run catalog` after adding or changing content. `npm run build` runs it too,
 * and a test fails if the committed catalog is out of date.
 */
import { writeFileSync } from "node:fs";
import { CR_ITEMS } from "../src/practice/cr";
import { RC_SETS } from "../src/practice/rc";
import { crMeta, rcLead, rcMeta, vaMeta } from "../src/practice/types";
import { VA_PARAS } from "../src/practice/va/paragraphs";

const rows = (xs: object[]) => xs.map((x) => "  " + JSON.stringify(x) + ",").join("\n");
const out = `// Generated by \`npm run catalog\` from the files in rc/, va/ and cr/. Do not edit by hand.
import type { CrMeta, RcMeta, VaMeta } from "./types";

export const RC_CATALOG: RcMeta[] = [
${rows(RC_SETS.map(rcMeta))}
];

export const VA_CATALOG: VaMeta[] = [
${rows(VA_PARAS.map(vaMeta))}
];

export const CR_CATALOG: CrMeta[] = [
${rows(CR_ITEMS.map(crMeta))}
];
`;
writeFileSync(new URL("../src/practice/catalog.gen.ts", import.meta.url), out);

const leads = `// Generated by \`npm run catalog\` from the files in rc/. Do not edit by hand.
// Its own file, so the home page loads it on demand and it stays out of the first download.

/** Each passage's opening paragraph: the text before its last sentence, and that sentence. */
export const RC_LEADS: Record<string, [string, string]> = {
${RC_SETS.map((s) => "  " + JSON.stringify(s.id) + ": " + JSON.stringify(rcLead(s)) + ",").join("\n")}
};
`;
writeFileSync(new URL("../src/practice/leads.gen.ts", import.meta.url), leads);
console.log(`catalog: ${RC_SETS.length} RC sets, ${VA_PARAS.length} VA paragraphs, ${CR_ITEMS.length} CR questions`);
