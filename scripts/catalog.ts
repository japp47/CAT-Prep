/**
 * Writes src/practice/catalog.gen.ts: titles, genres, word counts and dates for every RC set and VA paragraph.
 * The main bundle uses the catalog; the full passages load only when a practice page needs them.
 * Run with `npm run catalog` after adding or changing content. `npm run build` runs it too,
 * and a test fails if the committed catalog is out of date.
 */
import { writeFileSync } from "node:fs";
import { RC_SETS } from "../src/practice/rc";
import { rcMeta, vaMeta } from "../src/practice/types";
import { VA_PARAS } from "../src/practice/va/paragraphs";

const rows = (xs: object[]) => xs.map((x) => "  " + JSON.stringify(x) + ",").join("\n");
const out = `// Generated by \`npm run catalog\` from the files in rc/ and va/. Do not edit by hand.
import type { RcMeta, VaMeta } from "./types";

export const RC_CATALOG: RcMeta[] = [
${rows(RC_SETS.map(rcMeta))}
];

export const VA_CATALOG: VaMeta[] = [
${rows(VA_PARAS.map(vaMeta))}
];
`;
writeFileSync(new URL("../src/practice/catalog.gen.ts", import.meta.url), out);
console.log(`catalog: ${RC_SETS.length} RC sets, ${VA_PARAS.length} VA paragraphs`);
